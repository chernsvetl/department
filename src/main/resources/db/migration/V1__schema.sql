-- База данных кафедры общей информатики.
-- Структура повторяет сущности онтологии (ontologies/2022/4/кафедра):
--   department -> Кафедра           (название и заведующий)
--   person      -> Руководители (Руководитель_ВКР, Соруководитель_ВКР, Консультант,
--                  Руководитель_от_НГУ, Руководитель_от_организации) и Рецензент;
--                  колонки = свойства онтологии (Должность_руководителя_ВКР, Ученая_степень_руководителя_ВКР,
--                  ФИО_для_подписи, ДатаБакРук/ДатаМагМДА/ДатаМагТРПС/ДатаБакКнис и т.д.)
--   thesis      -> ВКР (Тема) и связи "согласовывает/руководит_с/консультирует/рецензирует"
--   student     -> Учащиеся (Бакалавриат/Магистратура): ФИО, группа, Профиль_обучения, свойство "защищает"
--   practice    -> Практика студента: Вид_практики, Место_прохождения_практики,
--                  Место_практики_полное_наименование, Наименование_организации,
--                  Приказ_на_прохождение_практики, "на_НГУ_практике_у", "на_орг_практике_у"

CREATE TABLE IF NOT EXISTS department (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL UNIQUE,
    head_name TEXT
);

CREATE TABLE IF NOT EXISTS person (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name             TEXT NOT NULL UNIQUE,
    thesis_position       TEXT,
    thesis_position_short TEXT,
    academic_degree       TEXT,
    position              TEXT,
    ngsu_position         TEXT,
    organization_position TEXT,
    signature_name        TEXT,
    bachelor_date         TEXT,
    bachelor_knis_date    TEXT,
    master_mda_date       TEXT,
    master_trps_date      TEXT
);

CREATE TABLE IF NOT EXISTS thesis (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic            TEXT UNIQUE,
    supervisor_id    INTEGER REFERENCES person (id),
    co_supervisor_id INTEGER REFERENCES person (id),
    consultant_id    INTEGER REFERENCES person (id),
    reviewer_id      INTEGER REFERENCES person (id)
);

CREATE TABLE IF NOT EXISTS student (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL REFERENCES department (id),
    degree        TEXT NOT NULL CHECK (degree IN ('Бакалавриат', 'Магистратура')),
    course        INTEGER NOT NULL,
    full_name     TEXT NOT NULL,
    group_name    TEXT NOT NULL DEFAULT '',
    profile       TEXT,
    thesis_id     INTEGER REFERENCES thesis (id),
    UNIQUE (degree, course, full_name, group_name)
);

CREATE TABLE IF NOT EXISTS practice (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                 INTEGER NOT NULL UNIQUE REFERENCES student (id),
    kind                       TEXT,
    place                      TEXT,
    full_place                 TEXT,
    organization_name          TEXT,
    order_number               TEXT,
    ngsu_supervisor_id         INTEGER REFERENCES person (id),
    organization_supervisor_id INTEGER REFERENCES person (id)
);
